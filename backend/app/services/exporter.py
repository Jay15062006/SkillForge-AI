import io
import re
import zipfile
from typing import Optional


def sanitize_folder_name(name: Optional[str]) -> str:
    """Sanitizes skill name for directory path safety."""
    if not name or not name.strip():
        return "custom-skill"
    cleaned = re.sub(r"[^a-zA-Z0-9-_]", "-", name.strip().lower())
    cleaned = re.sub(r"[-_]+", "-", cleaned).strip("-_")
    return cleaned or "custom-skill"


def create_skill_zip(skill_name: str, markdown_content: str) -> io.BytesIO:
    """
    Creates an in-memory ZIP package containing the skill folder, SKILL.md,
    and standard agent skill scaffolding (scripts, examples, references).
    """
    folder = sanitize_folder_name(skill_name)
    zip_buffer = io.BytesIO()

    with zipfile.ZipFile(zip_buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        # 1. Main SKILL.md inside skill folder
        zf.writestr(f"{folder}/SKILL.md", markdown_content)

        # 2. Skill README
        skill_readme = f"""# {folder}

Generated by SkillForge AI (Hacktoberfest 2026).

## Overview
This skill directory contains modular capability instructions for autonomous coding agents and LLM assistants.

## Structure
- `SKILL.md` - Core capability definitions, YAML frontmatter, and instructions.
- `scripts/` - Optional utility scripts or tools executed by the agent.
- `examples/` - Sample workflows, prompt examples, or task runs.
- `references/` - Supplementary API specs, cheat sheets, or manuals.

## Installation
Place this folder into your agent's skills directory:
- **Antigravity / Agentic IDE**: `.agents/skills/{folder}/`
- **Claude Code**: `.claude/skills/{folder}/`
- **Project Root**: `skills/{folder}/`
"""
        zf.writestr(f"{folder}/README.md", skill_readme)

        # 3. Scaffolding directories with helpful READMEs
        zf.writestr(
            f"{folder}/scripts/README.md",
            "# Scripts Directory\nPlace executable scripts, CLI helpers, or automation tools here that your agent can invoke.\n"
        )
        zf.writestr(
            f"{folder}/examples/README.md",
            "# Examples Directory\nPlace reference conversation transcripts, sample input/output pairs, or usage scenarios here.\n"
        )
        zf.writestr(
            f"{folder}/references/README.md",
            "# References Directory\nPlace relevant cheatsheets, API documentation, or domain guidelines here.\n"
        )

    zip_buffer.seek(0)
    return zip_buffer
